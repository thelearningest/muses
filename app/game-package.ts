import { VISUAL_LABEL_LIMITS } from "./game-capabilities";

export type ArtifactType =
  | "gate"
  | "switchboard"
  | "memory"
  | "constraints"
  | "console"
  | "kiosk";

export type Choice = {
  id: string;
  label: string;
  feedback: string;
  correct: boolean;
};

export type SourceAnchor = {
  label: string;
  pageStart: number;
  pageEnd: number;
};

export type VisualSpec = {
  mode: "diagram" | "3d" | "source-image";
  form: "portal" | "console" | "assembly" | "network" | "sequence" | "display";
  accent: "red" | "yellow" | "green";
  title: string;
  problemLabel: string;
  repairLabel: string;
  elements: [string, string, string];
  regions?: Array<{ imageIndex: number; label: string; x: number; y: number; width: number; height: number }>;
  // Trusted server attachments, never generated by the model.
  sourceImages?: Array<{ imageUrl: string; width: number; height: number; label: string }>;
};

export type Quest = {
  id: string;
  number: string;
  title: string;
  gallery: string;
  story: string;
  objective: string;
  clue: string;
  artifact: ArtifactType;
  xp: number;
  observationTools: string[];
  diagnosis: Choice[];
  repairs: Choice[];
  diagnosisQuestion?: string;
  repairQuestion?: string;
  principle: {
    name: string;
    summary: string;
  };
  visual?: VisualSpec;
  sourceAnchors?: SourceAnchor[];
};

export type GameContent = {
  sourceTitle: string;
  title: string;
  subtitle: string;
  setting: string;
  quests: Quest[];
};

export type GamePackage = GameContent & {
  schemaVersion: 1;
  id: string;
  sourceFilename: string;
  generatedAt: string;
};

const stringField = { type: "string", minLength: 1 } as const;

const choiceSchema = {
  type: "object",
  additionalProperties: false,
  required: ["id", "label", "feedback", "correct"],
  properties: {
    id: stringField,
    label: stringField,
    feedback: stringField,
    correct: { type: "boolean" },
  },
} as const;

export const QUEST_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: [
    "id", "number", "title", "gallery", "story", "objective", "clue", "artifact", "xp",
    "observationTools", "diagnosis", "repairs", "diagnosisQuestion", "repairQuestion", "principle", "visual", "sourceAnchors",
  ],
  properties: {
    id: stringField,
    number: stringField,
    title: stringField,
    gallery: stringField,
    story: stringField,
    objective: stringField,
    clue: stringField,
    artifact: { type: "string", enum: ["gate", "switchboard", "memory", "constraints", "console", "kiosk"] },
    xp: { type: "integer", minimum: 25, maximum: 200 },
    observationTools: { type: "array", minItems: 3, maxItems: 3, items: { ...stringField, maxLength: VISUAL_LABEL_LIMITS.observation } },
    diagnosis: { type: "array", minItems: 3, maxItems: 3, items: choiceSchema },
    repairs: { type: "array", minItems: 3, maxItems: 3, items: choiceSchema },
    diagnosisQuestion: stringField,
    repairQuestion: stringField,
    principle: {
      type: "object",
      additionalProperties: false,
      required: ["name", "summary"],
      properties: { name: stringField, summary: stringField },
    },
    visual: {
      type: "object",
      additionalProperties: false,
      required: ["mode", "form", "accent", "title", "problemLabel", "repairLabel", "elements", "regions"],
      properties: {
        mode: { type: "string", enum: ["source-image"] },
        form: { type: "string", enum: ["portal", "console", "assembly", "network", "sequence", "display"] },
        accent: { type: "string", enum: ["red", "yellow", "green"] },
        title: { ...stringField, maxLength: VISUAL_LABEL_LIMITS.title },
        problemLabel: { ...stringField, maxLength: VISUAL_LABEL_LIMITS.status },
        repairLabel: { ...stringField, maxLength: VISUAL_LABEL_LIMITS.status },
        elements: { type: "array", minItems: 3, maxItems: 3, items: { ...stringField, maxLength: VISUAL_LABEL_LIMITS.element } },
        regions: {
          type: "array", minItems: 2, maxItems: 3,
          items: {
            type: "object", additionalProperties: false,
            required: ["imageIndex", "label", "x", "y", "width", "height"],
            properties: {
              imageIndex: { type: "integer", minimum: 0, maximum: 1 },
              label: { ...stringField, maxLength: 48 },
              x: { type: "number", minimum: 0, maximum: 1 },
              y: { type: "number", minimum: 0, maximum: 1 },
              width: { type: "number", exclusiveMinimum: 0, maximum: 1 },
              height: { type: "number", exclusiveMinimum: 0, maximum: 1 },
            },
          },
        },
      },
    },
    sourceAnchors: {
      type: "array",
      minItems: 1,
      maxItems: 3,
      items: {
        type: "object",
        additionalProperties: false,
        required: ["label", "pageStart", "pageEnd"],
        properties: {
          label: stringField,
          pageStart: { type: "integer", minimum: 1 },
          pageEnd: { type: "integer", minimum: 1 },
        },
      },
    },
  },
} as const;

export const GAME_CONTENT_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["sourceTitle", "title", "subtitle", "setting", "quests"],
  properties: {
    sourceTitle: stringField,
    title: stringField,
    subtitle: stringField,
    setting: stringField,
    quests: {
      type: "array",
      minItems: 3,
      maxItems: 3,
      items: QUEST_SCHEMA,
    },
  },
} as const;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function isNonEmptyString(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0;
}

function validChoice(value: unknown): value is Choice {
  return (
    isRecord(value) &&
    isNonEmptyString(value.id) &&
    isNonEmptyString(value.label) &&
    isNonEmptyString(value.feedback) &&
    typeof value.correct === "boolean"
  );
}

function validVisual(value: unknown): boolean {
  if (!isRecord(value)) return false;
  return (
    ["diagram", "3d", "source-image"].includes(String(value.mode)) &&
    ["portal", "console", "assembly", "network", "sequence", "display"].includes(String(value.form)) &&
    ["red", "yellow", "green"].includes(String(value.accent)) &&
    [value.title, value.problemLabel, value.repairLabel].every(isNonEmptyString) &&
    Array.isArray(value.elements) &&
    value.elements.length === 3 &&
    value.elements.every(isNonEmptyString) &&
    (value.mode !== "source-image" || (
      Array.isArray(value.regions) && value.regions.length >= 2 && value.regions.length <= 3 &&
      value.regions.every((r) => isRecord(r) && Number.isInteger(r.imageIndex) && Number(r.imageIndex) >= 0 && Number(r.imageIndex) <= 1 &&
        isNonEmptyString(r.label) && [r.x, r.y, r.width, r.height].every((n) => typeof n === "number" && Number.isFinite(n)) &&
        Number(r.x) >= 0 && Number(r.y) >= 0 && Number(r.width) > 0 && Number(r.height) > 0 &&
        Number(r.x) + Number(r.width) <= 1.001 && Number(r.y) + Number(r.height) <= 1.001)
    )) &&
    (value.sourceImages === undefined || (Array.isArray(value.sourceImages) && value.sourceImages.length >= 1 && value.sourceImages.length <= 2 &&
      value.sourceImages.every((i) => isRecord(i) && typeof i.imageUrl === "string" && /^data:image\/(?:png|jpeg);base64,[A-Za-z0-9+/]+=*$/.test(i.imageUrl) &&
        Number.isInteger(i.width) && Number(i.width) > 0 && Number.isInteger(i.height) && Number(i.height) > 0 && isNonEmptyString(i.label))))
  );
}

function validQuest(value: unknown): value is Quest {
  if (!isRecord(value)) return false;
  const artifacts: ArtifactType[] = ["gate", "switchboard", "memory", "constraints", "console", "kiosk"];
  const diagnosis = value.diagnosis;
  const repairs = value.repairs;
  const anchors = value.sourceAnchors;
  return (
    [value.id, value.number, value.title, value.gallery, value.story, value.objective, value.clue].every(isNonEmptyString) &&
    artifacts.includes(value.artifact as ArtifactType) &&
    Number.isInteger(value.xp) &&
    Number(value.xp) >= 25 &&
    Array.isArray(value.observationTools) &&
    value.observationTools.length === 3 &&
    value.observationTools.every(isNonEmptyString) &&
    Array.isArray(diagnosis) &&
    diagnosis.length === 3 &&
    diagnosis.every(validChoice) &&
    diagnosis.filter((choice) => choice.correct).length === 1 &&
    Array.isArray(repairs) &&
    repairs.length === 3 &&
    repairs.every(validChoice) &&
    repairs.filter((choice) => choice.correct).length === 1 &&
    isRecord(value.principle) &&
    isNonEmptyString(value.principle.name) &&
    isNonEmptyString(value.principle.summary) &&
    (value.visual === undefined || validVisual(value.visual)) &&
    Array.isArray(anchors) &&
    anchors.length > 0 &&
    anchors.every(
      (anchor) =>
        isRecord(anchor) &&
        isNonEmptyString(anchor.label) &&
        Number.isInteger(anchor.pageStart) &&
        Number.isInteger(anchor.pageEnd) &&
        Number(anchor.pageStart) > 0 &&
        Number(anchor.pageEnd) >= Number(anchor.pageStart),
    )
  );
}

export function parseQuest(value: unknown): Quest | null {
  return validQuest(value) ? value : null;
}

export function parseGameContent(value: unknown): GameContent | null {
  if (!isRecord(value)) return null;
  if (
    !isNonEmptyString(value.sourceTitle) ||
    !isNonEmptyString(value.title) ||
    !isNonEmptyString(value.subtitle) ||
    !isNonEmptyString(value.setting) ||
    !Array.isArray(value.quests) ||
    value.quests.length < 1 ||
    value.quests.length > 9 ||
    !value.quests.every(validQuest)
  ) {
    return null;
  }
  return value as GameContent;
}

export function hasPlayableVisuals(game: GameContent): boolean {
  return game.quests.length > 0 && game.quests.every((quest) => quest.visual?.mode === "source-image" &&
    Boolean(quest.visual.sourceImages?.length) && Boolean(quest.diagnosisQuestion) && Boolean(quest.repairQuestion) &&
    Boolean(quest.visual.regions?.length) && quest.visual.regions!.every((r) => r.imageIndex < quest.visual!.sourceImages!.length));
}

export function hasRequiredVisualQuests(game: GameContent): boolean {
  return game.quests.length >= 3 && hasPlayableVisuals(game) &&
    new Set(game.quests.map((quest) => quest.visual!.sourceImages![0].imageUrl)).size >= 3;
}

export function isGamePackage(value: unknown): value is GamePackage {
  return (
    isRecord(value) &&
    value.schemaVersion === 1 &&
    isNonEmptyString(value.id) &&
    isNonEmptyString(value.sourceFilename) &&
    isNonEmptyString(value.generatedAt) &&
    parseGameContent(value) !== null
  );
}
